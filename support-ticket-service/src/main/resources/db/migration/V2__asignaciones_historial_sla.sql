-- asignación y control de SLA en el ticket
ALTER TABLE tickets
    ADD COLUMN tecnico_id              BIGINT REFERENCES tecnicos(id),
    ADD COLUMN fecha_limite_sla        TIMESTAMP NOT NULL,
    ADD COLUMN escalado                BOOLEAN   NOT NULL DEFAULT FALSE,
    ADD COLUMN fecha_primera_respuesta TIMESTAMP,
    ADD COLUMN fecha_resolucion        TIMESTAMP;

CREATE INDEX idx_tickets_tecnico ON tickets(tecnico_id);

-- trazabilidad de cada cambio
CREATE TABLE ticket_historial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id       BIGINT       NOT NULL REFERENCES tickets(id),
    accion          VARCHAR(20)  NOT NULL,
    estado_anterior VARCHAR(15),
    estado_nuevo    VARCHAR(15)  NOT NULL,
    observacion     VARCHAR(500),
    responsable     VARCHAR(150) NOT NULL,
    fecha           TIMESTAMP    NOT NULL
);

CREATE INDEX idx_historial_ticket ON ticket_historial(ticket_id);

-- horas límite por prioridad (configurables por el admin)
CREATE TABLE sla_politicas (
    prioridad    VARCHAR(10) PRIMARY KEY CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
    horas_limite INT NOT NULL CHECK (horas_limite > 0)
);

