-- usuarios del sistema (solicitantes, técnicos y admin)
CREATE TABLE usuarios (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento      VARCHAR(20)  NOT NULL UNIQUE,
    nombre         VARCHAR(120) NOT NULL,
    correo         VARCHAR(150) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    sede           VARCHAR(60)  NOT NULL,
    area           VARCHAR(60)  NOT NULL,
    estado         VARCHAR(10)  NOT NULL CHECK (estado IN ('ACTIVO','INACTIVO')),
    rol            VARCHAR(20)  NOT NULL CHECK (rol IN ('ROLE_USUARIO','ROLE_TECNICO','ROLE_ADMIN'))
);

-- perfil técnico enlazado a un usuario
CREATE TABLE tecnicos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(10)  NOT NULL UNIQUE,
    usuario_id     BIGINT       NOT NULL UNIQUE REFERENCES usuarios(id),
    nombre         VARCHAR(120) NOT NULL,
    especialidad   VARCHAR(10)  NOT NULL CHECK (especialidad IN ('HARDWARE','SOFTWARE','RED','ACCESOS','OTRO')),
    sede           VARCHAR(60)  NOT NULL,
    carga_maxima   INT          NOT NULL CHECK (carga_maxima > 0),
    estado         VARCHAR(10)  NOT NULL CHECK (estado IN ('ACTIVO','INACTIVO'))
);

-- datos básicos del ticket
CREATE TABLE tickets (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id  BIGINT       NOT NULL REFERENCES usuarios(id),
    titulo          VARCHAR(150) NOT NULL,
    descripcion     VARCHAR(2000) NOT NULL,
    categoria       VARCHAR(10)  NOT NULL CHECK (categoria IN ('HARDWARE','SOFTWARE','RED','ACCESOS','OTRO')),
    prioridad       VARCHAR(10)  NOT NULL CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
    sede            VARCHAR(60)  NOT NULL,
    activo_afectado VARCHAR(120) NOT NULL,
    estado          VARCHAR(15)  NOT NULL CHECK (estado IN ('ABIERTO','ASIGNADO','EN_PROGRESO','RESUELTO','CERRADO','CANCELADO')),
    fecha_creacion  TIMESTAMP    NOT NULL
);

CREATE INDEX idx_tickets_solicitante ON tickets(solicitante_id);
CREATE INDEX idx_tickets_estado ON tickets(estado);
